// LOCAL integrity verification only. Never contacts GitHub/Supabase/Vercel.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const read=p=>JSON.parse(readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const policy=read('config/production-strategy.json'),s=policy.sourceCandidate;
assert.equal(policy.supabasePlan,'free');assert.equal(policy.maximumSupabaseMonthlyChargeUsd,0);
for(const k of ['paidChangesAllowed','newOrganizationsAllowed','newProjectsAllowed','candidateFormallyAdopted','closedSiteBackendBindingApproved','productionDeploymentApproved','registrationEnabled','emailDeliveryEnabled','activationApproved'])assert.equal(policy[k],false,k);
assert.equal(hash(s.inventoryPath),s.inventorySha256);
const inventory=read(s.inventoryPath),repo=resolve(s.directory);
const git=(...args)=>{const r=spawnSync('git',args,{cwd:repo,windowsHide:true,encoding:'utf8'});assert.equal(r.status,0);return r.stdout.trim();};
assert.equal(git('rev-parse','HEAD'),s.commit);assert.equal(git('rev-parse','HEAD^{tree}'),s.tree);
assert.equal(git('status','--porcelain'),'');assert.equal(git('remote','-v'),'');
assert.deepEqual(git('diff','--name-only',s.parent,s.commit).split('\n'),['config/test-target.json']);
assert.equal(inventory.files.length,172);
for(const f of inventory.files)assert.equal(hash(resolve(repo,f.path)),f.sha256,f.path);
assert.deepEqual(read(resolve(repo,'config/test-target.json')),{projectRef:policy.candidateProject});
const v=read('artifacts/free-only-site-review-20261031-v1/verification-v2/validation.json');
assert.equal(v.status,'PASSED_OFFLINE');assert.equal(v.unitTests,25);assert.equal(v.externalRequestsAttempted,0);
assert.equal(read('config/production-clean-address-review.json').status,'SUPERSEDED_BY_FREE_ONLY_STRATEGY');
assert.equal(read('config/phase3-hosted-preview-acceptance.json').Phase3Accepted,true);
const obs=read('.secrets/free-only-strategy-review-20261031-v1/sanitized-observations.json');
assert.equal(obs.organization.plan,'free');assert.equal(obs.projects.length,2);
assert.deepEqual(obs.projects.map(p=>p.id).sort(),[policy.originalProject,policy.candidateProject].sort());
assert(obs.projects.every(p=>p.status==='ACTIVE_HEALTHY'));
console.log(JSON.stringify({localIntegrity:'PASSED',reviewedSourceFiles:172,originalAndPreviewProjectsPreserved:true,paidPlanSuperseded:true,publicationApproved:false,productionDeployed:false,hostedRequests:0}));
